# Summary
print_summary() {
    echo ""
    echo "=== Extraction Complete ==="
    echo ""
    echo "Component: $COMPONENT"
    echo "Location: $DEST_DIR"
    echo ""
    echo "Next steps:"
    echo "  1. Review $DEST_DIR/ANALYSIS.md"
    echo "  2. Check $DEST_DIR/DEPENDENCIES.txt"
    echo "  3. Update $DEST_DIR/Makefile.bsd"
