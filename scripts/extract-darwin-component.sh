#!/bin/sh
# CatBSD Darwin Component Extraction Script
# Extracts a Darwin component from Apple OSS and prepares it for porting

set -e

# Check arguments
if [ $# -lt 1 ]; then
    echo "Usage: $0 <component-name>"
    echo ""
    echo "Examples:"
    echo "  $0 launchd"
    echo "  $0 libdispatch"
    echo "  $0 CF"
    echo ""
    exit 1
fi

COMPONENT=$1

echo "=== Extracting Darwin Component: $COMPONENT ==="
echo ""

# Load environment
if [ -f .catbsd.env ]; then
    . ./.catbsd.env
else
    CATBSD_ROOT="$(pwd)"
    CATBSD_SRC="$CATBSD_ROOT/src"
fi

APPLE_DIR="$CATBSD_SRC/apple-oss"
DARWIN_COMPAT="$CATBSD_SRC/darwin-compat"
DEST_DIR="$DARWIN_COMPAT/$COMPONENT"

# Check if Apple OSS exists
if [ ! -d "$APPLE_DIR" ]; then
    echo "Error: Apple OSS not found at $APPLE_DIR"
    echo "Run ./scripts/fetch-sources.sh first"
    exit 1
fi

# Find component in Apple OSS
find_component() {
    echo "Searching for $COMPONENT in Apple OSS..."
    
    # Try exact match
    if [ -d "$APPLE_DIR/$COMPONENT" ]; then
        SRC_DIR="$APPLE_DIR/$COMPONENT"
        echo "  ✓ Found: $SRC_DIR"
        return 0
    fi
    
    # Try case-insensitive search
    FOUND=$(find "$APPLE_DIR" -maxdepth 1 -iname "$COMPONENT" -type d 2>/dev/null | head -n1)
    if [ -n "$FOUND" ]; then
        SRC_DIR="$FOUND"
        echo "  ✓ Found: $SRC_DIR"
        return 0
    fi
    
    echo "  ✗ Component not found"
    echo ""
    echo "Available components:"
    ls -1 "$APPLE_DIR" | head -20
    exit 1
}

# Copy component
copy_component() {
    echo ""
    echo "Copying $COMPONENT to darwin-compat/..."
    
    mkdir -p "$DEST_DIR"
    cp -R "$SRC_DIR"/* "$DEST_DIR/" 2>/dev/null || cp -R "$SRC_DIR" "$DARWIN_COMPAT/"
    
    echo "  ✓ Copied to $DEST_DIR"
}

# Analyze dependencies
analyze_dependencies() {
    echo ""
    echo "Analyzing dependencies..."
    
    DEP_FILE="$DEST_DIR/DEPENDENCIES.txt"
    
    # Find includes
    echo "System includes:" > "$DEP_FILE"
    find "$DEST_DIR" -name "*.c" -o -name "*.h" -o -name "*.cpp" 2>/dev/null | \
        xargs grep -h "^#include <" 2>/dev/null | \
        sort -u >> "$DEP_FILE" || true
    
    echo "" >> "$DEP_FILE"
    echo "Mach/Darwin specific:" >> "$DEP_FILE"
    grep -E "(mach/|darwin/|os/|CoreFoundation/|dispatch/)" "$DEP_FILE" | head -20 >> "$DEP_FILE.tmp" || true
    mv "$DEP_FILE.tmp" "$DEP_FILE" 2>/dev/null || true
    
    # Find syscalls
    echo "" >> "$DEP_FILE"
    echo "Syscalls and kernel APIs:" >> "$DEP_FILE"
    find "$DEST_DIR" -name "*.c" 2>/dev/null | \
        xargs grep -h "syscall\|mach_\|xpc_\|IOKit" 2>/dev/null | \
        head -20 >> "$DEP_FILE" || true
    
    echo "  ✓ Dependencies analyzed: $DEP_FILE"
}

# Create Makefile template
create_makefile() {
    echo ""
    echo "Creating Makefile template..."
    
    MAKEFILE="$DEST_DIR/Makefile.bsd"
    
    # Determine if it's a library or program
    if echo "$COMPONENT" | grep -qi "^lib"; then
        TYPE="library"
        TARGET="LIB"
    else
        TYPE="program"
        TARGET="PROG"
    fi
    
    cat > "$MAKEFILE" << EOF
# FreeBSD Makefile for $COMPONENT
# Generated by extract-darwin-component.sh

# Component type: $TYPE
$TARGET=   $COMPONENT

# Source files (update this list)
SRCS=   # TODO: Add source files

# Include paths
CFLAGS+= -I.
CFLAGS+= -I../shims
CFLAGS+= -DFREEBSD_COMPAT

# Warnings
CFLAGS+= -Wall -Wextra

# Dependencies (update as needed)
# LDADD=  -lpthread -lutil
# DPADD=  \${LIBPTHREAD} \${LIBUTIL}

# FreeBSD compatibility shims
LDADD+= -L../shims -ldarwin_compat

.include <bsd.prog.mk>
# Or for libraries: .include <bsd.lib.mk>
EOF

    echo "  ✓ Created: $MAKEFILE"
    echo "    (Edit this file to add source files and dependencies)"
}

